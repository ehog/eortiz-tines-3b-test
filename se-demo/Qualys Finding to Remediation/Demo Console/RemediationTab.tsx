import { useEffect, useState } from "react";
import { api, type Finding } from "./api";
import type { Shell } from "./App";
import { Badge, Button, Card, CodeBlock, Empty, bandTone } from "./ui";

function confidenceTone(confidence: string): string {
  if (confidence === "high") return "success";
  if (confidence === "medium") return "medium";
  return "low";
}

export default function RemediationTab({ shell }: { shell: Shell }) {
  const { notify, run } = shell;
  const [findings, setFindings] = useState<Finding[] | null>(null);
  const [stage, setStage] = useState<string | null>(null);
  const [runId, setRunId] = useState<string | null>(null);

  const load = async () => {
    try {
      const res = await api.enrichedFindings();
      setFindings(res.findings);
      setStage(res.stage);
      setRunId(res.run_id);
    } catch (err) {
      notify(`Could not load remediation packages: ${(err as Error).message}`, "error");
    }
  };

  useEffect(() => {
    void load();
  }, []);

  const withPackages = (findings ?? []).filter((f) => f.remediation);
  const generated = withPackages.filter((f) => f.remediation!.source === "model");
  const belowThreshold = withPackages.filter((f) => f.remediation!.source !== "model");

  return (
    <div className="space-y-4">
      <Card
        title="AI remediation packages"
        subtitle={
          runId
            ? `From pipeline run ${runId} (${stage} stage). ${generated.length} generated by the model, ${belowThreshold.length} summarised deterministically.`
            : "No pipeline run recorded yet."
        }
        actions={
          <>
            <Button busy={shell.busy === "Regenerate packages"} onClick={() =>
              void run("Regenerate packages", async () => {
                await api.runStage("remediate");
                await load();
              })
            }>
              Regenerate packages
            </Button>
            <Button variant="ghost" onClick={() => void load()}>
              Refresh
            </Button>
          </>
        }
      >
        {!findings ? (
          <Empty>Loading…</Empty>
        ) : withPackages.length === 0 ? (
          <Empty>
            No remediation packages yet. Run the pipeline from the Pipeline tab — the AI stage runs on
            findings scoring at or above the high-priority threshold.
          </Empty>
        ) : (
          <div className="space-y-4">
            {[...generated, ...belowThreshold].map((f) => (
              <PackageCard key={f.finding_id} finding={f} />
            ))}
          </div>
        )}
      </Card>
    </div>
  );
}

function PackageCard({ finding }: { finding: Finding }) {
  const pkg = finding.remediation!;
  const isModel = pkg.source === "model";

  return (
    <article className="rounded-[10px] border border-[var(--border)] bg-[var(--card-solid)]">
      <header className="flex flex-wrap items-start justify-between gap-3 border-b border-[var(--divider)] px-4 py-3">
        <div className="min-w-0">
          <div className="flex flex-wrap items-center gap-2">
            <span className="font-semibold">{finding.finding_id}</span>
            {finding.risk && <Badge tone={bandTone(finding.risk.risk_band)}>{finding.risk.risk_band} · {finding.risk.risk_score}</Badge>}
            <Badge tone="neutral">{finding.finding_type.replace(/_/g, " ")}</Badge>
            {isModel ? (
              <Badge tone="info">AI generated</Badge>
            ) : (
              <Badge tone="neutral">Qualys solution text only</Badge>
            )}
            {isModel && <Badge tone={confidenceTone(pkg.confidence)}>{pkg.confidence} confidence</Badge>}
          </div>
          <div className="mt-1 text-[13px]">{finding.title}</div>
          <div className="mt-1 text-[12px] text-[var(--text-secondary)]">
            {finding.asset.hostname} · {finding.asset.os} · {finding.owner.team}
          </div>
        </div>
        <div className="text-right text-[12px] text-[var(--text-secondary)]">
          <div>
            Reboot:{" "}
            <span className={pkg.reboot_required ? "font-semibold text-[var(--orange)]" : "font-semibold"}>
              {pkg.reboot_required ? "required" : "not required"}
            </span>
          </div>
          <div>Target version: {pkg.fix_version ?? "n/a"}</div>
        </div>
      </header>

      <div className="space-y-4 p-4">
        {!pkg.determinable ? (
          <div className="rounded-md border border-[var(--orange)]/40 bg-[var(--orange)]/10 p-3">
            <div className="text-[13px] font-semibold text-[#a1521c]">
              Cannot determine a fix from the available evidence
            </div>
            <p className="mt-1 text-[12.5px] leading-relaxed text-[#8a4a1c]">{pkg.summary}</p>
            {pkg.missing_evidence.length > 0 && (
              <ul className="mt-2 list-disc space-y-0.5 pl-5 text-[12.5px] text-[#8a4a1c]">
                {pkg.missing_evidence.map((m) => (
                  <li key={m}>Missing: {m}</li>
                ))}
              </ul>
            )}
          </div>
        ) : (
          <p className="text-[13px] leading-relaxed">{pkg.summary}</p>
        )}

        <div className="grid gap-3 lg:grid-cols-2">
          <div className="rounded-md border border-[var(--border)] bg-[var(--card-bg)] p-3">
            <div className="text-[11px] font-semibold tracking-wide text-[var(--text-secondary)] uppercase">
              Required fix
            </div>
            <p className="mt-1.5 text-[12.5px] leading-relaxed">{pkg.required_fix}</p>
            <div className="mt-2 text-[12px] text-[var(--text-secondary)]">
              Service impact: {pkg.service_impact}
            </div>
          </div>

          {pkg.prerequisites.length > 0 && (
            <div className="rounded-md border border-[var(--border)] bg-[var(--card-bg)] p-3">
              <div className="text-[11px] font-semibold tracking-wide text-[var(--text-secondary)] uppercase">
                Prerequisites
              </div>
              <ul className="mt-1.5 list-disc space-y-1 pl-5 text-[12.5px]">
                {pkg.prerequisites.map((p) => (
                  <li key={p}>{p}</li>
                ))}
              </ul>
            </div>
          )}
        </div>

        {pkg.commands.length > 0 && (
          <div className="space-y-2">
            <div className="text-[11px] font-semibold tracking-wide text-[var(--text-secondary)] uppercase">
              Change steps
            </div>
            {pkg.commands.map((c, i) => (
              <div key={`${c.command}-${i}`}>
                <div className="mb-1 text-[12px] text-[var(--text-secondary)]">{c.description}</div>
                <CodeBlock code={c.command} label={c.platform} />
              </div>
            ))}
          </div>
        )}

        {pkg.code_fix && (
          <div className="space-y-2">
            <div className="text-[11px] font-semibold tracking-wide text-[var(--text-secondary)] uppercase">
              Secure-code fix — {pkg.code_fix.file}
            </div>
            <p className="text-[12.5px] leading-relaxed">{pkg.code_fix.note}</p>
            <div className="grid gap-2 lg:grid-cols-2">
              <div>
                <div className="mb-1 flex items-center gap-2 text-[12px] font-semibold text-[var(--red)]">
                  <span className="rounded bg-[var(--red)]/12 px-1.5 py-0.5">− before</span>
                </div>
                <CodeBlock code={pkg.code_fix.before} label={pkg.code_fix.language} />
              </div>
              <div>
                <div className="mb-1 flex items-center gap-2 text-[12px] font-semibold text-[var(--green)]">
                  <span className="rounded bg-[var(--green)]/12 px-1.5 py-0.5">+ after</span>
                </div>
                <CodeBlock code={pkg.code_fix.after} label={pkg.code_fix.language} />
              </div>
            </div>
          </div>
        )}

        <div className="grid gap-3 lg:grid-cols-2">
          {pkg.validation.length > 0 && (
            <div className="rounded-md border border-[var(--border)] bg-[var(--card-bg)] p-3">
              <div className="text-[11px] font-semibold tracking-wide text-[var(--text-secondary)] uppercase">
                Validation
              </div>
              <ul className="mt-1.5 list-disc space-y-1 pl-5 text-[12.5px]">
                {pkg.validation.map((v) => (
                  <li key={v}>{v}</li>
                ))}
              </ul>
            </div>
          )}

          {pkg.evidence_citations.length > 0 && (
            <div className="rounded-md border border-[var(--accent)]/25 bg-[var(--accent-soft)]/60 p-3">
              <div className="text-[11px] font-semibold tracking-wide text-[var(--accent-deep)] uppercase">
                Qualys evidence cited
              </div>
              <ul className="mt-1.5 space-y-1">
                {pkg.evidence_citations.map((e, i) => (
                  <li
                    key={`${e}-${i}`}
                    className="rounded border border-[var(--accent)]/20 bg-white/60 px-2 py-1 font-mono text-[11.5px] break-words"
                  >
                    {e}
                  </li>
                ))}
              </ul>
            </div>
          )}
        </div>
      </div>
    </article>
  );
}
